// Metadata only; original files remain untouched and load on demand.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const folder = path.join(root, 'assets/trader-wisdom');
function walk(dir) { return fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : /\.(png|jpe?g|webp|gif)$/i.test(e.name) ? [path.relative(root,path.join(dir,e.name)).replaceAll('\\','/')] : []); }
const items = walk(folder).sort((a,b)=>a.localeCompare(b,'en',{numeric:true}));
fs.writeFileSync(path.join(root,'assets/wisdom-index.json'),JSON.stringify({items}));
// A classic script also works when index.html is opened directly (file://).
fs.writeFileSync(path.join(root,'frontend/trader-wisdom-index.js'),`/* Generated by scripts/build-wisdom-index.cjs; original assets are not modified. */\nwindow.traderWisdomAssetPaths = ${JSON.stringify(items)};\n`);
console.log(`${items.length} original images indexed`);
